_SEP_RE = re.compile(r'[()（）>≫→・,、､，/|：:\[\]0-9\s+＋*×.．。°%：第发~〜]+')
_ASCII = re.compile(r'[A-Za-z]')

def combo_translate(s: str) -> str | None:
    """整条字符串可完全分解为已知 token + 分隔符时返回译文，否则 None"""
    s = re.sub(r'(\d+)発目', r'第\1发', s)
    s = re.sub(r'(\d+)発', r'\1发', s)
    out, i, n = [], 0, len(s)
    while i < n:
        # token 最长匹配优先（避免分隔符类抢先吃掉 BD/N 等字母）
        for tok, zh in TOKENS:  # TOKENS 按长度降序
            if s.startswith(tok, i):
                out.append(zh)
                i += len(tok)
                break
        else:
            # 分隔符/数字 直通；ASCII 字母单字符直通（避免 BD 被粘连吞掉）
            m = _SEP_RE.match(s, i)
            if m and m.end() > i:
                out.append(m.group())
                i = m.end()
            elif _ASCII.match(s, i):
                out.append(s[i])
                i += 1
            else:
                return None
    return ''.join(out)

# 按 token 长度降序排列保证最长匹配
TOKENS.sort(key=lambda kv: -len(kv[0]))

def auto_translate(s: str) -> tuple[str, str | None]:
    """返回 (结果, 方式)。方式: ext / combo / None"""
    st = s.strip()
    if not st:
        return s, 'ext'
    if st in EXT:
        pre, suf = s[:len(s)-len(s.lstrip())], s[len(s.rstrip()):]
        return pre + EXT[st] + suf, 'ext'
    t = combo_translate(s)
    if t is not None and t != s:
        return t, 'combo'
    return s, None

