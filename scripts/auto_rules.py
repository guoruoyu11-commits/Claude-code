_norm_cache: dict[str, str] = {}

def build_norm_book(book: dict[str, str]) -> dict[str, str]:
    nb = {}
    for s, t in book.items():
        k = re.sub(r'\s+', '', s)
        if k and k not in nb:
            nb[k] = t
    return nb

def norm_lookup(v: str, norm_book: dict[str, str]) -> str | None:
    k = re.sub(r'\s+', '', v)
    if not k:
        return None
    return norm_book.get(k)
