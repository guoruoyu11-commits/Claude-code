#!/usr/bin/env python3
"""把散图合并成雪碧图，降低 CDN 请求数。

生成两类雪碧图（默认 WebP，--format png 可切换）：
  1. 机体缩略图 —— 按 cost 分组，每组一张：
       public/images/sprites/machines-{cost}.webp
  2. Cost 筛选按钮图标（8 张 640x160）合成一张：
       public/images/sprites/cost-icons.webp

同时生成前端定位用的 manifest：
  src/data/sprite_manifest.js   （MACHINE_SPRITES / COST_SPRITE）

用法：
  python3 scripts/make_sprite.py                 # WebP, quality 90
  python3 scripts/make_sprite.py --format png
  python3 scripts/make_sprite.py --quality 85
"""

import argparse
import math
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
MACHINES_JS = ROOT / "src" / "data" / "machines.js"
MACHINE_IMG_DIR = ROOT / "public" / "images" / "machines"
COST_IMG_DIR = ROOT / "public" / "images" / "cost"
SPRITE_DIR = ROOT / "public" / "images" / "sprites"
MANIFEST_JS = ROOT / "src" / "data" / "sprite_manifest.js"

MACHINE_COLS = 8   # 机体雪碧图每行列数
COST_COLS = 2      # cost 图标雪碧图每行列数


def parse_machine_costs():
    """从 machines.js 提取 {图片编号: cost} 映射。"""
    text = MACHINES_JS.read_text(encoding="utf-8")
    pat = re.compile(r"cost:\s*'?(\d{4})'?[^}]*?img:\s*'/images/machines/(\d+)\.png'")
    return {num: int(cost) for cost, num in pat.findall(text)}


def pack_sheet(images, cols, out_path, fmt, quality):
    """把同尺寸图片按网格拼成一张雪碧图，返回 (cols, rows, {key: (col, row)})。"""
    size = images[0][1].size
    for key, img in images:
        if img.size != size:
            sys.exit(f"[abort] 图片尺寸不一致: {key} 是 {img.size}，应为 {size}")

    cols = max(2, cols)  # 至少 2 列，避免 CSS 百分比定位除零
    rows = math.ceil(len(images) / cols)
    sheet = Image.new("RGBA", (cols * size[0], rows * size[1]), (0, 0, 0, 0))

    cells = {}
    for i, (key, img) in enumerate(images):
        col, row = i % cols, i // cols
        sheet.paste(img, (col * size[0], row * size[1]))
        cells[key] = (col, row)

    if fmt == "webp":
        sheet.save(out_path, "WEBP", quality=quality, method=6)
    else:
        sheet.save(out_path, "PNG", optimize=True)
    return cols, rows, cells


def main():
    ap = argparse.ArgumentParser(description="生成机体/cost 雪碧图与 manifest")
    ap.add_argument("--format", choices=["webp", "png"], default="webp")
    ap.add_argument("--quality", type=int, default=90)
    args = ap.parse_args()
    ext = args.format

    SPRITE_DIR.mkdir(parents=True, exist_ok=True)

    # ── 1. 机体缩略图，按 cost 分组 ──────────────────────
    num_to_cost = parse_machine_costs()
    by_cost = {}
    for f in sorted(MACHINE_IMG_DIR.glob("*.png")):
        cost = num_to_cost.get(f.stem)
        if cost is None:
            print(f"[warn] {f.name} 未在 machines.js 中引用，跳过")
            continue
        by_cost.setdefault(cost, []).append((f.stem, Image.open(f)))

    machine_sprites = {}
    for cost in sorted(by_cost, reverse=True):
        items = by_cost[cost]
        out = SPRITE_DIR / f"machines-{cost}.{ext}"
        cols, rows, cells = pack_sheet(items, MACHINE_COLS, out, ext, args.quality)
        machine_sprites[cost] = {
            "url": f"/images/sprites/machines-{cost}.{ext}",
            "cols": cols,
            "rows": rows,
            "cells": cells,
        }
        print(f"[ok] {out.name}: {len(items)} 张 {cols}x{rows} 网格, "
              f"{out.stat().st_size / 1024:.0f} KB")

    # ── 2. Cost 筛选图标 ────────────────────────────────
    cost_items = [(f.stem.replace("cost", ""), Image.open(f))
                  for f in sorted(COST_IMG_DIR.glob("cost*.png"))]
    cost_out = SPRITE_DIR / f"cost-icons.{ext}"
    c_cols, c_rows, c_cells = pack_sheet(cost_items, COST_COLS, cost_out, ext, args.quality)
    cost_sprite = {
        "url": f"/images/sprites/cost-icons.{ext}",
        "cols": c_cols,
        "rows": c_rows,
        "cells": c_cells,
    }
    print(f"[ok] {cost_out.name}: {len(cost_items)} 张 {c_cols}x{c_rows} 网格, "
          f"{cost_out.stat().st_size / 1024:.0f} KB")

    # ── 3. 生成 manifest.js ─────────────────────────────
    def cells_js(cells):
        body = ", ".join(f"'{k}': [{c},{r}]" for k, (c, r) in cells.items())
        return "{" + body + "}"

    lines = [
        "// AUTO-GENERATED by scripts/make_sprite.py -- 请勿手改。",
        "// cells: { 图片编号: [col, row] }",
        "export const MACHINE_SPRITES = {",
    ]
    for cost, s in machine_sprites.items():
        lines.append(
            f"  {cost}: {{ url: '{s['url']}', cols: {s['cols']}, rows: {s['rows']}, "
            f"cells: {cells_js(s['cells'])} }},"
        )
    lines += [
        "}",
        "",
        "export const COST_SPRITE = {",
        f"  url: '{cost_sprite['url']}', cols: {c_cols}, rows: {c_rows}, "
        f"cells: {cells_js(c_cells)},",
        "}",
        "",
    ]
    MANIFEST_JS.write_text("\n".join(lines), encoding="utf-8")
    print(f"[ok] {MANIFEST_JS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
