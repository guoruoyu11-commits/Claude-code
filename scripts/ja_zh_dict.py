_JA_RE = re.compile(r"[぀-ヿ一-鿿豈-﫿]")


def has_japanese(text: str) -> bool:
    """文本中是否含有日文字符（平假名、片假名、汉字区）。"""
    return bool(_JA_RE.search(text))


def apply_dict(text: str) -> tuple[str, bool]:
    """
    对文本做精确全串匹配（strip 后）。
    返回 (结果文本, 是否命中字典)。
    命中时返回字典译文（保留原始首尾空白）；否则原样返回。
    """
    stripped = text.strip()
    if stripped in TERMS:
        # 保留原始首尾空白（节点文本可能有缩进）
        prefix = text[: len(text) - len(text.lstrip())]
        suffix = text[len(text.rstrip()):]
        return prefix + TERMS[stripped] + suffix, True
    return text, False
